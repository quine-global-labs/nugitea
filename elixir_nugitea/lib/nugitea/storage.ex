defmodule Nugitea.Storage do
  @moduledoc """
  The storage tier: owns the repo root and runs every git process, the way
  Gitaly does for GitLab. It trusts its caller; access checks happen once, in
  the app tier, before anything gets here.

  These functions run on the storage node. The app tier reaches them through
  `Nugitea.Storage.Client`: Erlang distribution and nothing else, no protocol
  of our own. With NUGITEA_ROLE=all the "remote" node is this one.

  Repos are addressed by path (`owner/name`, `org/sub-org/name`), laid out
  on disk as `<root>/<path>.git`.
  """

  alias Nugitea.Names

  @services %{"upload-pack" => "upload-pack", "receive-pack" => "receive-pack"}
  @hooks ~w(pre-receive update post-receive)

  # ---- repos --------------------------------------------------------------

  def dir(path) do
    with :ok <- Names.validate_repo_path(path), do: {:ok, Path.join(root(), path <> ".git")}
  end

  def exists?(path) do
    case dir(path) do
      {:ok, dir} -> File.dir?(dir)
      {:error, _} -> false
    end
  end

  @doc "Every repo under the root, as paths; walks owner dirs, not into repos."
  def list, do: list_under(root(), [])

  defp list_under(dir, owners) do
    for entry <- File.ls!(dir), File.dir?(Path.join(dir, entry)), reduce: [] do
      acc ->
        case String.split_at(entry, -4) do
          {name, ".git"} when owners != [] -> [Enum.join(owners ++ [name], "/") | acc]
          {_, ".git"} -> acc
          _ -> acc ++ list_under(Path.join(dir, entry), owners ++ [entry])
        end
    end
    |> Enum.sort()
  end

  @doc """
  `git init --bare`, then hook delegators, as Gitea's InitRepository and
  CreateDelegateHooks do.
  """
  def init_bare(path) do
    with {:ok, dir} <- dir(path) do
      if File.exists?(dir) do
        {:error, "repo #{inspect(path)} already exists"}
      else
        File.mkdir_p!(dir)
        :ok = git(dir, ["init", "--bare", "--quiet", "."])
        install_hooks(dir)
      end
    end
  end

  # Gitea's hooks/<name> delegate to `gitea hook <name>`. nugitea's hooks
  # don't do anything yet (no protected branches, no webhooks), so each is a
  # stub that accepts the push: the landing spot for future policy.
  defp install_hooks(dir) do
    for name <- @hooks do
      hook = Path.join([dir, "hooks", name])

      File.write!(
        hook,
        "#!/bin/sh\n# AUTO GENERATED BY NUGITEA, DO NOT MODIFY\ncat >/dev/null\nexit 0\n"
      )

      File.chmod!(hook, 0o755)
    end

    :ok
  end

  @doc "A unary git command in the repo, for mirrors (remote add/remove, fetch, push --mirror)."
  def run_git(path, args) do
    with {:ok, dir} <- dir(path), do: git(dir, args)
  end

  # ---- smart HTTP and SSH ----------------------------------------------

  @doc "The ref advertisement that starts a smart-HTTP exchange (`GET .../info/refs`)."
  def info_refs(path, service, protocol \\ nil) do
    with {:ok, dir} <- existing(path),
         {:ok, cmd} <- service(service) do
      {out, 0} =
        System.cmd("git", [cmd, "--stateless-rpc", "--advertise-refs", dir],
          env: protocol_env(protocol)
        )

      pkt = "# service=git-#{cmd}\n"
      {:ok, [pkt_len(pkt), pkt, "0000", out]}
    end
  end

  defp pkt_len(pkt),
    do:
      (byte_size(pkt) + 4)
      |> Integer.to_string(16)
      |> String.pad_leading(4, "0")
      |> String.downcase()

  @doc """
  Runs `git <service>` for one exchange, started on this node by the app
  tier. Input arrives as `{ref, :input, chunk}` messages then `{ref, :eof}`;
  git's output goes back to `reply_to` as `{ref, :output, chunk}`, then
  `{ref, :exit, status}`. Both directions stream at once, so this serves
  smart HTTP (`stateless: true`, one request then the response) and SSH's
  interactive protocol alike.

  `protocol` is the client's Git-Protocol header (e.g. "version=2"), passed
  to git as GIT_PROTOCOL; `gzip` inflates gzipped HTTP request bodies.
  """
  def exchange(reply_to, ref, path, service, opts) do
    {:ok, dir} = existing(path)
    {:ok, cmd} = service(service)
    args = if opts[:stateless], do: [cmd, "--stateless-rpc", dir], else: [cmd, dir]

    git = System.find_executable("git")

    {:ok, _pid, os_pid} =
      :exec.run([git | args], [:stdin, :stdout, :monitor, {:env, protocol_env(opts[:protocol])}])

    inflater = opts[:gzip] && inflater()
    loop(reply_to, ref, os_pid, inflater)
  end

  defp loop(reply_to, ref, os_pid, inflater) do
    receive do
      {^ref, :input, chunk} ->
        :exec.send(
          os_pid,
          if(inflater, do: IO.iodata_to_binary(:zlib.inflate(inflater, chunk)), else: chunk)
        )

        loop(reply_to, ref, os_pid, inflater)

      {^ref, :eof} ->
        if inflater, do: :zlib.close(inflater)
        :exec.send(os_pid, :eof)
        loop(reply_to, ref, os_pid, nil)

      {:stdout, ^os_pid, chunk} ->
        send(reply_to, {ref, :output, chunk})
        loop(reply_to, ref, os_pid, inflater)

      {:DOWN, ^os_pid, :process, _, reason} ->
        send(reply_to, {ref, :exit, exit_status(reason)})
    end
  end

  defp exit_status(:normal), do: 0
  defp exit_status({:exit_status, status}), do: :exec.status(status) |> elem(1)
  defp exit_status(_), do: 1

  defp inflater do
    z = :zlib.open()
    # 31 = gzip header + max window
    :ok = :zlib.inflateInit(z, 31)
    z
  end

  # The client's Git-Protocol header (HTTP) or GIT_PROTOCOL env (SSH), e.g.
  # "version=2", as git's GIT_PROTOCOL; only what git actually sends.
  defp protocol_env(proto) when is_binary(proto) do
    if proto =~ ~r/\A[A-Za-z0-9=;,._-]+\z/, do: [{"GIT_PROTOCOL", proto}], else: []
  end

  defp protocol_env(nil), do: []

  # ---- file browser -----------------------------------------------------

  @doc "Local branch names."
  def branches(path) do
    with {:ok, dir} <- existing(path),
         {:ok, out} <- capture(dir, ["for-each-ref", "--format=%(refname:short)", "refs/heads"]) do
      {:ok, String.split(out, "\n", trim: true)}
    end
  end

  @doc "One level of the tree at `ref:path` (or `ref`'s root): `%{name, kind, sha}`."
  def tree(path, ref, subpath) do
    treeish = if subpath == "", do: ref, else: "#{ref}:#{subpath}"

    with {:ok, dir} <- existing(path),
         :ok <- no_leading_dash([ref, subpath]),
         {:ok, out} <- capture(dir, ["ls-tree", treeish]) do
      entries =
        for line <- String.split(out, "\n", trim: true),
            [meta, name] = String.split(line, "\t", parts: 2),
            [_mode, kind, sha] = String.split(meta, " "),
            # commit (submodule) entries aren't browsable
            kind in ["tree", "blob"],
            do: %{name: name, kind: String.to_existing_atom(kind), sha: sha}

      {:ok, entries}
    end
  end

  @doc "The blob at `ref:path`: `%{sha, content}` (raw bytes)."
  def blob(path, ref, subpath) do
    treeish = "#{ref}:#{subpath}"

    with {:ok, dir} <- existing(path),
         :ok <- no_leading_dash([ref, subpath]),
         :ok <- if(subpath == "", do: {:error, "empty path"}, else: :ok),
         {:ok, sha} <- capture(dir, ["rev-parse", treeish]),
         {:ok, content} <- capture(dir, ["cat-file", "blob", treeish]) do
      {:ok, %{sha: String.trim(sha), content: content}}
    end
  end

  @doc "Every file path in `ref`'s tree, recursively (the search feature's list)."
  def files(path, ref) do
    with {:ok, dir} <- existing(path),
         :ok <- no_leading_dash([ref]),
         {:ok, out} <- capture(dir, ["ls-tree", "-r", "--name-only", ref]) do
      {:ok, String.split(out, "\n", trim: true)}
    end
  end

  @doc "The default branch of a repository (`git symbolic-ref --short HEAD`)."
  def default_branch(path) do
    with {:ok, dir} <- existing(path),
         {:ok, out} <- capture(dir, ["symbolic-ref", "--short", "HEAD"]) do
      {:ok, String.trim(out)}
    end
  end

  @doc "Sets the default branch of a repository (refusing a branch that doesn't exist)."
  def set_default_branch(path, branch) do
    with {:ok, dir} <- existing(path),
         {:ok, _out} <- capture(dir, ["show-ref", "--verify", "refs/heads/#{branch}"]) do
      :ok = git(dir, ["symbolic-ref", "HEAD", "refs/heads/#{branch}"])
      :ok
    end
  end

  # git would read a leading "-" as an option, not a ref or path.
  defp no_leading_dash(args) do
    case Enum.find(args, &String.starts_with?(&1, "-")) do
      nil -> :ok
      arg -> {:error, "invalid ref or path #{inspect(arg)}"}
    end
  end

  # ---- helpers ----------------------------------------------------------

  defp existing(path) do
    with {:ok, dir} <- dir(path) do
      if File.dir?(dir), do: {:ok, dir}, else: {:error, :not_found}
    end
  end

  defp service(name) do
    case @services do
      %{^name => cmd} -> {:ok, cmd}
      _ -> {:error, :bad_service}
    end
  end

  defp git(dir, args) do
    case System.cmd("git", ["-C", dir | args], stderr_to_stdout: true) do
      {_, 0} -> :ok
      {out, status} -> {:error, "git #{hd(args)} exited #{status}: #{String.trim(out)}"}
    end
  end

  defp capture(dir, args) do
    case System.cmd("git", ["-C", dir | args], stderr_to_stdout: false) do
      {out, 0} -> {:ok, out}
      {_, status} -> {:error, "git #{hd(args)} exited #{status}"}
    end
  end

  @doc "Delete a repository directory from disk."
  def delete(path) do
    with {:ok, dir} <- dir(path) do
      if File.dir?(dir) do
        File.rm_rf!(dir)
        :ok
      else
        {:error, :not_found}
      end
    end
  end

  @doc """
  Returns the size of a repository in KiB, using `git count-objects -v`.
  The result is the sum of `size` and `size-pack` from git count-objects.
  """
  def size(path) do
    with {:ok, dir} <- existing(path) do
      case capture(dir, ["count-objects", "-v"]) do
        {:ok, output} ->
          # Parse the output to extract size and size-pack
          size =
            output
            |> String.split("\n")
            |> Enum.reduce(0, fn line, acc ->
              case Regex.run(~r/^size:\s+(\d+)/, line) do
                [_, size_str] -> acc + String.to_integer(size_str)
                _ -> acc
              end
            end)

          size_pack =
            output
            |> String.split("\n")
            |> Enum.reduce(0, fn line, acc ->
              case Regex.run(~r/^size-pack:\s+(\d+)/, line) do
                [_, size_pack_str] -> acc + String.to_integer(size_pack_str)
                _ -> acc
              end
            end)

          {:ok, size + size_pack}

        _ ->
          {:error, "Unable to determine size"}
      end
    end
  end

  defp root, do: Application.fetch_env!(:nugitea, :repo_root)
end
